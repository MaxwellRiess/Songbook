#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { argv } from "node:process";
import { pathToFileURL } from "node:url";

// The Shortcuts action takes one pasted block of JavaScript, so the readers the
// extension injects as separate files have to arrive as a single snippet. The
// order matters: chord-utils and the two readers define the globals that the
// dispatcher looks up, and the entry runs last.
const SOURCE_FILES = [
  "extension/chord-utils-content.js",
  "extension/guitartuna-content.js",
  "extension/ultimate-guitar-content.js",
  "extension/clipper-content.js",
  "extension/shortcut-entry.js"
];

const OUTPUT_FILE = "public/shortcut/songbook-clip.js";

const HEADER = `// Songbook clipper for the iOS Shortcuts action "Run JavaScript on Web Page".
//
// Generated by scripts/build-shortcut.js from:
${SOURCE_FILES.map((file) => `//   ${file}`).join("\n")}
//
// Do not edit this file. Edit the sources and run \`npm run build:shortcut\`.
`;

export async function buildShortcutSnippet(root = new URL("../", import.meta.url)) {
  const parts = await Promise.all(
    SOURCE_FILES.map(async (file) => (await readFile(new URL(file, root), "utf8")).trim())
  );
  return `${HEADER}\n${parts.join("\n\n")}\n`;
}

export { OUTPUT_FILE, SOURCE_FILES };

if (argv[1] && import.meta.url === pathToFileURL(argv[1]).href) {
  const root = new URL("../", import.meta.url);
  const target = new URL(OUTPUT_FILE, root);
  await mkdir(new URL("./", target), { recursive: true });
  await writeFile(target, await buildShortcutSnippet(root));
  console.log(`Wrote ${OUTPUT_FILE}`);
}
